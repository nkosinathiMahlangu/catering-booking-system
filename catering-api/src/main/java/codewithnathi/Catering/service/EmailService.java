package codewithnathi.Catering.service;

import lombok.RequiredArgsConstructor;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.mail.SimpleMailMessage;
import org.springframework.mail.javamail.JavaMailSender;
import org.springframework.stereotype.Service;

/**
 * Handles all outbound email communication for the catering system.
 * <p>
 * Uses Spring's {@link JavaMailSender} backed by Gmail SMTP (configured in
 * application.yaml). The sender address is bound from {@code spring.mail.username}
 * so it stays consistent with the authenticated SMTP account.
 * </p>
 */
@Service
@RequiredArgsConstructor
public class EmailService {

    private final JavaMailSender mailSender;

    /** The "from" address — must match the authenticated SMTP username. */
    @Value("${spring.mail.username}")
    private String fromEmail;

    /**
     * Sends a one-time password to the user for identity verification.
     * The OTP expires in 2 minutes; that deadline is enforced by {@link UserService}.
     *
     * @param to      the recipient's email address
     * @param otpCode the 6-digit OTP generated by {@link UserService#initiatePasswordReset}
     */
    public void sendOtpEmail(String to, String otpCode) {
        SimpleMailMessage message = new SimpleMailMessage();
        message.setFrom(fromEmail);
        message.setTo(to);
        message.setSubject("Your OTP Code");
        message.setText("Your OTP is: " + otpCode + ". It expires in 2 minutes.");
        mailSender.send(message);
    }

    /**
     * Sends a generic booking-related email (confirmation, invoice, cancellation notice).
     * The caller is responsible for composing a meaningful subject and body.
     *
     * @param to      the recipient's email address
     * @param subject the email subject line
     * @param body    the plain-text email body
     */
    public void sendBookingConfirmation(String to, String subject, String body) {
        SimpleMailMessage message = new SimpleMailMessage();
        message.setFrom(fromEmail);
        message.setTo(to);
        message.setSubject(subject);
        message.setText(body);
        mailSender.send(message);
    }
}
